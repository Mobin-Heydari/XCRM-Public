/**
 * Resolve a catalog URL to a real destination. Never returns a dead link.
 *
 * Allowed: in-page anchors from a whitelist, registry feature slugs,
 * known site routes and the external dashboard. Anything else falls back
 * to $fallback (or '' when no fallback is given).
 *
 * @param string $url      Raw catalog URL (path, anchor or absolute).
 * @param string $fallback Fallback URL when $url is not verifiable.
 * @return string
 */
function xcrm_fd_resolve_url( $url, $fallback = '' ) {
	$url = trim( (string) $url );
	if ( '' === $url ) {
		return $fallback;
	}

	// External dashboard — always valid.
	if ( 0 === strpos( $url, 'https://dashboard.xcrmforosh.com' ) ) {
		return $url;
	}

	// In-page anchors: whitelist of section ids rendered by this template.
	if ( 0 === strpos( $url, '#' ) ) {
		$allowed_anchors = array( '#catalog', '#journey', '#usecases', '#faq', '#cta', '#cat-customers', '#cat-tracking', '#cat-analytics', '#cat-segmentation', '#cat-sales', '#cat-automation', '#cat-communication', '#cat-integrations', '#cat-templates', '#cat-team', '#cat-billing', '#cat-experience' );
		return in_array( $url, $allowed_anchors, true ) ? $url : $fallback;
	}

	// Registry-backed feature slugs (built pages only).
	if ( preg_match( '#^/features/([a-z0-9-]+)/?$#', $url, $m ) ) {
		$feature = function_exists( 'xcrm_get_feature' ) ? xcrm_get_feature( $m[1] ) : null;
		if ( $feature && ! empty( $feature['built'] ) ) {
			return home_url( '/features/' . $feature['slug'] . '/' );
		}
		return $fallback;
	}

	// Known static routes.
	$known = array( '/', '/features/', '/for-marketers/', '/for-business/', '/privacy-policy/', '/terms/' );
	$norm  = untrailingslashit( $url ) . '/';
	if ( in_array( $norm, $known, true ) || in_array( untrailingslashit( $url ), array_map( 'untrailingslashit', $known ), true ) ) {
		return home_url( $norm );
	}

	return $fallback;
}

